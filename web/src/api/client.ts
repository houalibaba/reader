export interface ChildProfile {
  id: string;
  name: string;
  avatar: string;
  learning_stage: string;
  created_at: string;
}

export interface StorySummary {
  id: string;
  title: string;
  theme: string;
  description: string;
  cover_url: string;
  latest_version_id: string;
  version_number: number;
  sentence_count: number;
  active_session_id?: string;
  resume_sentence_index: number;
  review_char_count: number;
  recommended_reason?: string;
}

export interface SentenceToken {
  id: string;
  token_index?: number;
  character: string;
  pinyin: string;
  word: string;
  word_index: number;
  audio_url: string;
  is_polyphone?: boolean;
}

export interface StorySentence {
  id: string;
  sequence_index: number;
  text: string;
  image_url: string;
  audio_url: string;
  tokens: SentenceToken[];
}

export interface StoryVersionDetail {
  story_id: string;
  version_id: string;
  version_number: number;
  title: string;
  theme: string;
  description: string;
  cover_url: string;
  sentences: StorySentence[];
}

export interface ReadingSession {
  id: string;
  child_id: string;
  story_version_id: string;
  mode: 'solo' | 'accompanied';
  status: 'active' | 'completed' | 'abandoned';
  current_sentence_index: number;
  resumed: boolean;
  started_at: string;
}

export interface VocabularyEntry {
  character: string;
  pinyin: string;
  exposure_count: number;
  helped_view_count: number;
  help_count: number;
  last_help_at: string;
  estimated_status: 'needs_support' | 'insufficient_evidence' | 'likely_familiar';
}

export interface PlanTargetItem {
  character: string;
  pinyin: string;
  help_count: number;
  exposure_count: number;
  recommended_words: string[];
  target_repetitions: number;
  retention_pct?: number;
  forgetting_stage?: string;
  urgency?: number;
  reason: string;
}

export interface StoryPlanResponse {
  child_id: string;
  summary?: Record<string, any>;
  reading_science?: Record<string, any>;
  review_targets: PlanTargetItem[];
  observe_targets: PlanTargetItem[];
  familiar_anchors: PlanTargetItem[];
  new_candidates: PlanTargetItem[];
  story_generation_prompt: string;
}

export interface AutoGeneratedStoryResponse {
  title: string;
  theme: string;
  description: string;
  raw_text: string;
  sentences: string[];
  image_prompts?: string[];
  generator: string;
  review_words: string[];
  review_chars: string[];
  published: boolean;
  imported_story_id?: string;
  imported_version_id?: string;
  version_number?: number;
  sentence_count?: number;
  cover_url?: string;
  image_urls?: string[];
}

export interface CustomImageUploadPayload {
  sentence_index?: number;
  filename: string;
  data_base64: string;
}

export interface GistStoryPullResponse {
  status: 'imported' | 'already_imported';
  version: string;
  imported_story_id?: string;
  imported_version_id?: string;
  version_number?: number;
  title: string;
  theme: string;
  description: string;
  raw_text: string;
  sentences: string[];
  sentence_count: number;
  image_count: number;
  lines_per_image: string;
  cover_url?: string;
  image_urls?: string[];
  source: string;
}

export interface HealthStatusResponse {
  status: string;
  version: string;
  arch: string;
  free_disk_mb: number;
  disk_space_ok: boolean;
  min_free_disk_mb: number;
  disk_error?: string;
}

export interface UpdateCheckResponse {
  current_version: string;
  latest_version: string;
  has_update: boolean;
  release_url?: string;
  release_notes?: string;
  published_at?: string;
  asset_name?: string;
  download_url?: string;
}

export interface UpdateApplyResponse {
  status: string;
  previous_version?: string;
  new_version?: string;
  exe_path?: string;
  message?: string;
}

export const apiClient = {
  async getHealth(): Promise<HealthStatusResponse> {
    const res = await fetch('/api/v1/health');
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },

  async listChildren(): Promise<ChildProfile[]> {
    const res = await fetch('/api/v1/children');
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    return data.children || [];
  },

  async createChild(payload: { name: string; avatar: string; learning_stage?: string }): Promise<ChildProfile> {
    const res = await fetch('/api/v1/children', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },

  async deleteChild(pin: string, childId: string): Promise<{ deleted: string }> {
    const res = await fetch(`/api/v1/children/${encodeURIComponent(childId)}`, {
      method: 'DELETE',
      headers: { 'X-Guardian-Pin': pin }
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`);
    return data;
  },

  async listStories(childId?: string): Promise<StorySummary[]> {
    const q = childId ? `?child_id=${encodeURIComponent(childId)}` : '';
    const res = await fetch(`/api/v1/stories${q}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    return data.stories || [];
  },

  async getStoryVersion(storyId: string, versionId: string): Promise<StoryVersionDetail> {
    const res = await fetch(`/api/v1/stories/${encodeURIComponent(storyId)}/versions/${encodeURIComponent(versionId)}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },

  async deleteStory(pin: string, storyId: string, hard = false): Promise<{ deleted: string; title: string }> {
    const q = hard ? '?hard=1' : '';
    const res = await fetch(`/api/v1/admin/stories/${encodeURIComponent(storyId)}${q}`, {
      method: 'DELETE',
      headers: { 'X-Guardian-Pin': pin }
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`);
    return data;
  },

  async startOrResumeSession(payload: {
    child_id: string;
    story_version_id: string;
    mode: 'solo' | 'accompanied';
    pinyin_hint_enabled: boolean;
    force_new?: boolean;
  }): Promise<ReadingSession> {
    const res = await fetch('/api/v1/sessions', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },

  async getVocabulary(childId: string): Promise<VocabularyEntry[]> {
    const res = await fetch(`/api/v1/children/${encodeURIComponent(childId)}/vocabulary`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    return data.vocabulary || [];
  },

  async getStoryPlan(childId: string): Promise<StoryPlanResponse> {
    const res = await fetch(`/api/v1/children/${encodeURIComponent(childId)}/story-plan`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return res.json();
  },

  async autoGenerateStory(
    pin: string,
    payload: {
      child_id?: string;
      theme?: string;
      auto_publish: boolean;
      llm_api_url?: string;
      llm_api_key?: string;
      llm_model?: string;
      image_api_url?: string;
      image_api_key?: string;
      image_model?: string;
    }
  ): Promise<AutoGeneratedStoryResponse> {
    const res = await fetch('/api/v1/admin/auto-generate-story', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Guardian-Pin': pin
      },
      body: JSON.stringify(payload)
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || data.detail || `HTTP ${res.status}`);
    return data;
  },

  async quickCreateOrUpdateStory(
    pin: string,
    payload: {
      story_id?: string;
      title: string;
      theme?: string;
      description?: string;
      raw_text: string;
      custom_images?: CustomImageUploadPayload[];
      image_api_url?: string;
      image_api_key?: string;
      image_model?: string;
    }
  ): Promise<{
    imported_story_id: string;
    imported_version_id: string;
    version_number: number;
    sentence_count: number;
    cover_url?: string;
  }> {
    const res = await fetch('/api/v1/admin/quick-story', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Guardian-Pin': pin
      },
      body: JSON.stringify(payload)
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || data.detail || `HTTP ${res.status}`);
    return data;
  },

  async pullStoryFromGist(
    pin: string,
    force = false
  ): Promise<GistStoryPullResponse> {
    const res = await fetch('/api/v1/admin/gist-pull', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Cache-Control': 'no-cache',
        'X-Guardian-Pin': pin
      },
      body: JSON.stringify({ force })
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || data.detail || `HTTP ${res.status}`);
    return data;
  },

  async importStoryZip(
    pin: string,
    file: File
  ): Promise<{ imported_story_id: string; imported_version_id: string; sentence_count: number }> {
    const form = new FormData();
    form.append('package', file);
    const res = await fetch('/api/v1/admin/import', {
      method: 'POST',
      headers: { 'X-Guardian-Pin': pin },
      body: form
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`);
    return data;
  },

  async checkSystemUpdate(pin: string, mirrorUrl = ''): Promise<UpdateCheckResponse> {
    const q = mirrorUrl.trim() ? `?mirror_url=${encodeURIComponent(mirrorUrl.trim())}` : '';
    const res = await fetch(`/api/v1/admin/update/check${q}`, {
      headers: { 'X-Guardian-Pin': pin }
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`);
    return data;
  },

  async applySystemUpdate(pin: string, mirrorUrl = ''): Promise<UpdateApplyResponse> {
    const res = await fetch('/api/v1/admin/update/apply', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Guardian-Pin': pin
      },
      body: JSON.stringify({ mirror_url: mirrorUrl.trim() })
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`);
    return data;
  },

  async markEventValidity(eventId: string, isValid: boolean, pin: string, reason?: string): Promise<void> {
    const res = await fetch(`/api/v1/admin/events/${encodeURIComponent(eventId)}/validity`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'X-Guardian-Pin': pin
      },
      body: JSON.stringify({
        is_valid: isValid,
        reason: reason || 'guardian_marked_accidental'
      })
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
  }
};
