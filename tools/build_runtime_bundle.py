#!/usr/bin/env python3
"""Build a deterministic, versioned Reader runtime bundle and its Go bootstrap payload."""
from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]


def _file_entry(path: Path, relative: str) -> tuple[tarfile.TarInfo, bytes]:
    payload = path.read_bytes()
    info = tarfile.TarInfo(relative)
    info.size = len(payload)
    executable = relative == "reader_menu.sh" or relative.endswith(".sh") or relative in {
        "deploy/reader.init",
        "deploy/99-reader-hotplug",
    }
    info.mode = 0o755 if executable else 0o644
    info.mtime = 0
    info.uid = info.gid = 0
    info.uname = info.gname = ""
    info.type = tarfile.REGTYPE
    return info, payload


def build(version: str, commit: str, archive: Path, go_output: Path) -> None:
    if not version or "/" in version or ".." in version:
        raise ValueError(f"unsafe version: {version!r}")
    archive = archive if archive.is_absolute() else ROOT / archive
    go_output = go_output if go_output.is_absolute() else ROOT / go_output

    runtime_files: list[tuple[str, Path]] = [("reader_menu.sh", ROOT / "reader_menu.sh")]
    runtime_files.extend(
        (p.relative_to(ROOT).as_posix(), p)
        for p in sorted((ROOT / "tools").rglob("*"))
        if p.is_file() and not p.is_symlink() and p.suffix in {".py", ".sh"}
    )
    runtime_files.extend(
        (p.relative_to(ROOT).as_posix(), p)
        for p in sorted((ROOT / "deploy").rglob("*"))
        if p.is_file() and not p.is_symlink()
    )
    required = {
        "reader_menu.sh",
        "tools/menu.py",
        "tools/story_packager.py",
        "tools/vocab_planner.py",
        "deploy/deploy_to_istoreos.sh",
        "deploy/reader.init",
        "deploy/99-reader-hotplug",
        "deploy/config.json",
    }
    paths = {name for name, _ in runtime_files}
    missing = required - paths
    if missing:
        raise FileNotFoundError(f"required runtime files missing: {sorted(missing)}")

    entries = []
    payloads: list[tuple[str, tarfile.TarInfo, bytes]] = []
    for relative, source in runtime_files:
        info, content = _file_entry(source, relative)
        entries.append({
            "path": relative,
            "size": len(content),
            "sha256": hashlib.sha256(content).hexdigest(),
        })
        payloads.append((relative, info, content))

    manifest = json.dumps(
        {"format_version": 1, "version": version, "commit": commit, "files": entries},
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    manifest_info = tarfile.TarInfo("runtime-manifest.json")
    manifest_info.size = len(manifest)
    manifest_info.mode = 0o644
    manifest_info.mtime = 0
    manifest_info.uid = manifest_info.gid = 0
    manifest_info.uname = manifest_info.gname = ""
    manifest_info.type = tarfile.REGTYPE

    archive.parent.mkdir(parents=True, exist_ok=True)
    with archive.open("wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0, compresslevel=9) as gz:
            with tarfile.open(fileobj=gz, mode="w", format=tarfile.USTAR_FORMAT) as tar:
                tar.addfile(manifest_info, io.BytesIO(manifest))
                for _, info, content in payloads:
                    tar.addfile(info, io.BytesIO(content))

    encoded = base64.b64encode(archive.read_bytes()).decode("ascii")
    chunks = [encoded[i : i + 100] for i in range(0, len(encoded), 100)] or [""]
    go_output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Code generated by tools/build_runtime_bundle.py; DO NOT EDIT.",
        "package updater",
        "",
        "const embeddedRuntimeBundleBase64 =",
    ]
    lines.extend(f'\t"{chunk}" +' for chunk in chunks[:-1])
    lines.append(f'\t"{chunks[-1]}"')
    go_output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Built {archive.relative_to(ROOT)} ({archive.stat().st_size} bytes) and {go_output.relative_to(ROOT)}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--commit", default=os.environ.get("GITHUB_SHA", "local"))
    parser.add_argument("--archive", type=Path, default=ROOT / "dist/reader-runtime.tar.gz")
    parser.add_argument(
        "--go-output",
        type=Path,
        default=ROOT / "server/internal/updater/runtime_payload_gen.go",
    )
    args = parser.parse_args()
    build(args.version, args.commit, args.archive, args.go_output)


if __name__ == "__main__":
    main()
